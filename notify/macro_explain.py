def now_text(slug: str, value_str: str, unit: str, badge: dict, note: str | None) -> str:
    """④ 지금 수치는 어떻게 읽나요 — 오늘 값과 판정을 넣은 문장 (순수 함수).

    입력: slug, value_str(표시용 값), unit, badge(core.macro_status.classify_macro 결과), note(보조 설명)
    출력: 예) "오늘 값은 5.17%로, 기준표의 🔴 위험 칸(4.5% 이상)에 있어요. 금리가 높아 ... (3개월 변화 +0.30%p)"
    """
    current = next((row for row in badge.get("scale", []) if row.get("current")), None)
    where = f"기준표의 {badge['text']} 칸({current['range']})에 있어요." if current else f"{badge['text']} 상태예요."
    shown_unit = "" if unit == "/100" else unit
    text = f"오늘 값은 {value_str}{shown_unit}로, {where} {_NOW_HINT.get(slug, {}).get(badge['status'], '')}".strip()
    if note:
        text += f" ({note})"
    return text
